import { useState } from 'react'
import { useQuery } from '@tanstack/react-query'
import { Search, RefreshCw } from 'lucide-react'
import api from '../../../api/client'
import { DatePicker } from '../../../components/DatePicker'

// Human-readable action labels
const ACTION_LABELS = {
  ADMIN_LOGIN:        'Admin Logged In',
  ADMIN_LOGOUT:       'Admin Logged Out',
  GENERATE_INVOICE:   'Invoice Generated',
  UPDATE_SETTINGS:    'Settings Updated',
  APPROVE_MEMBER:     'Application Approved',
  REJECT_MEMBER:      'Application Rejected',
  REVIEW_MEMBER:      'Application Moved to Review',
  PAYMENT_APPROVED:   'Payment Verified',
  PAYMENT_REJECTED:   'Payment Rejected',
  CREATE_USER:        'Admin User Created',
  UPDATE_USER:        'Admin User Updated',
  DELETE_USER:        'Admin User Deleted',
  RESET_PASSWORD:     'Password Reset',
  SUSPEND_MEMBER:     'Member Suspended',
  ACTIVATE_MEMBER:    'Member Activated',
  RENEWAL_VERIFIED:   'Renewal Verified',
  RENEWAL_REJECTED:   'Renewal Rejected',
}

// Module display badges
const MODULE_COLORS = {
  auth:         'bg-blue-100 text-blue-700',
  applications: 'bg-purple-100 text-purple-700',
  payments:     'bg-green-100 text-green-700',
  members:      'bg-teal-100 text-teal-700',
  renewals:     'bg-orange-100 text-orange-700',
  invoices:     'bg-yellow-100 text-yellow-700',
  users:        'bg-gray-100 text-gray-700',
  settings:     'bg-slate-100 text-slate-700',
}

const MODULE_LABELS = {
  auth: 'AUTH', applications: 'APPLICATIONS', payments: 'PAYMENTS',
  members: 'MEMBERS', renewals: 'RENEWALS', invoices: 'INVOICES',
  users: 'USERS', settings: 'SETTINGS',
  approvals: 'APPLICATIONS', forms: 'FORMS', submissions: 'APPLICATIONS',
  packages: 'PACKAGES', certificates: 'CERTIFICATES',
}

function getDetails(entry) {
  const who = entry.admin_name || 'Admin'
  const id = entry.record_id ? `#${entry.record_id}` : ''
  switch (entry.action) {
    case 'ADMIN_LOGIN':      return `${who} logged into the admin panel`
    case 'ADMIN_LOGOUT':     return `${who} logged out`
    case 'GENERATE_INVOICE': return `Invoice ${id} generated by ${who}`
    case 'APPROVE_MEMBER':   return `Application ${id} approved by ${who}`
    case 'REJECT_MEMBER':    return `Application ${id} rejected by ${who}`
    case 'REVIEW_MEMBER':    return `Application ${id} moved to review by ${who}`
    case 'PAYMENT_APPROVED': return `Payment ${id} verified by ${who}`
    case 'PAYMENT_REJECTED': return `Payment ${id} rejected by ${who}`
    case 'CREATE_USER':      return `Admin user ${id} created by ${who}`
    case 'UPDATE_USER':      return `Admin user ${id} updated by ${who}`
    case 'DELETE_USER':      return `Admin user ${id} deleted by ${who}`
    case 'RESET_PASSWORD':   return `Password reset for user ${id} by ${who}`
    case 'SUSPEND_MEMBER':   return `Member ${id} suspended by ${who}`
    case 'ACTIVATE_MEMBER':  return `Member ${id} activated by ${who}`
    case 'UPDATE_SETTINGS':  return `System settings updated by ${who}`
    case 'RENEWAL_VERIFIED': return `Renewal ${id} verified and expiry updated by ${who}`
    case 'RENEWAL_REJECTED': return `Renewal ${id} rejected by ${who}`
    default:                 return entry.action ? `${entry.action.replace(/_/g, ' ')} ${id} by ${who}` : `Action by ${who}`
  }
}

export default function AuditLog() {
  const [filters, setFilters] = useState({ q: '', module: '', from: '', to: '', page: 1 })

  const { data, isLoading, refetch } = useQuery({
    queryKey: ['audit-log', filters],
    queryFn: () => {
      const params = new URLSearchParams()
      Object.entries(filters).forEach(([k, v]) => { if (v) params.set(k, v) })
      return api.get(`/audit?${params}`).then(r => r.data.data)
    },
    keepPreviousData: true,
  })

  const { data: modules } = useQuery({
    queryKey: ['audit-modules'],
    queryFn: () => api.get('/audit/modules').then(r => r.data.data || [])
  })

  const log = data?.data || []
  const total = data?.total || 0
  const totalPages = data?.totalPages || 1

  return (
    <div className="space-y-5">
      <div className="flex items-center justify-between">
        <h2 className="text-2xl font-bold text-gray-900">Audit Log</h2>
        <button className="btn-outline" onClick={() => refetch()}><RefreshCw size={14}/> Refresh</button>
      </div>

      {/* Filters */}
      <div className="card card-body">
        <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-3">
          <div className="relative">
            <Search size={16} className="absolute left-3 top-1/2 -translate-y-1/2 text-gray-400"/>
            <input className="input pl-9" placeholder="Search action, module…" value={filters.q}
              onChange={e => setFilters(f => ({ ...f, q: e.target.value, page: 1 }))} />
          </div>
          <select className="input" value={filters.module}
            onChange={e => setFilters(f => ({ ...f, module: e.target.value, page: 1 }))}>
            <option value="">All Modules</option>
            {(Array.isArray(modules) ? modules : []).map(m => (
              <option key={m} value={m}>{m}</option>
            ))}
          </select>
          <DatePicker value={filters.from} onChange={v => setFilters(f => ({ ...f, from: v, page: 1 }))} placeholder="From date" />
          <DatePicker value={filters.to} onChange={v => setFilters(f => ({ ...f, to: v, page: 1 }))} placeholder="To date" />
        </div>
      </div>

      {/* Table */}
      <div className="card overflow-hidden">
        <div className="px-4 py-3 border-b flex items-center justify-between">
          <span className="text-sm text-gray-500">{total} records</span>
        </div>
        <div className="overflow-x-auto">
          <table className="w-full text-sm">
            <thead className="bg-gray-50 border-b">
              <tr>
                <th className="px-4 py-3 text-left font-medium text-gray-600">Date &amp; Time</th>
                <th className="px-4 py-3 text-left font-medium text-gray-600">User</th>
                <th className="px-4 py-3 text-left font-medium text-gray-600">Module</th>
                <th className="px-4 py-3 text-left font-medium text-gray-600">Action</th>
                <th className="px-4 py-3 text-left font-medium text-gray-600">Details</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-gray-100">
              {isLoading ? (
                <tr><td colSpan={5} className="py-12 text-center text-gray-400">Loading…</td></tr>
              ) : log.map(entry => (
                <tr key={entry.id} className="hover:bg-gray-50">
                  <td className="px-4 py-3 text-xs text-gray-500 whitespace-nowrap">
                    {new Date(entry.created_at).toLocaleString('en-IN', { dateStyle: 'short', timeStyle: 'short' })}
                  </td>
                  <td className="px-4 py-3">
                    <div className="font-medium text-xs text-gray-900">{entry.admin_name || 'System'}</div>
                    <div className="text-xs text-gray-400">{entry.admin_email}</div>
                  </td>
                  <td className="px-4 py-3">
                    <span className={`text-xs font-semibold px-2 py-0.5 rounded-full ${MODULE_COLORS[entry.module] || 'bg-gray-100 text-gray-600'}`}>
                      {MODULE_LABELS[entry.module] || (entry.module || '').toUpperCase()}
                    </span>
                  </td>
                  <td className="px-4 py-3 text-xs text-gray-800 font-medium">
                    {ACTION_LABELS[entry.action] || entry.action?.replace(/_/g, ' ')}
                  </td>
                  <td className="px-4 py-3 text-xs text-gray-500">{getDetails(entry)}</td>
                </tr>
              ))}
              {!isLoading && log.length === 0 && (
                <tr><td colSpan={5} className="py-12 text-center text-gray-400">No audit logs found.</td></tr>
              )}
            </tbody>
          </table>
        </div>
        {totalPages > 1 && (
          <div className="px-4 py-3 border-t flex items-center justify-between text-sm">
            <span className="text-gray-500">Page {filters.page} of {totalPages}</span>
            <div className="flex gap-2">
              <button className="btn-outline btn-sm" disabled={filters.page <= 1}
                onClick={() => setFilters(f => ({ ...f, page: f.page - 1 }))}>Previous</button>
              <button className="btn-outline btn-sm" disabled={filters.page >= totalPages}
                onClick={() => setFilters(f => ({ ...f, page: f.page + 1 }))}>Next</button>
            </div>
          </div>
        )}
      </div>
    </div>
  )
}
